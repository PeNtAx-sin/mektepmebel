const key = () => randomUUID().slice(0, 12);

function spans(text) {
  const markDefs = [];
  const children = [];
  let last = 0;
  for (const m of text.matchAll(/\[([^\]]+)\]\(([^)]+)\)/g)) {
    if (m.index > last) children.push({ _type: "span", _key: key(), text: text.slice(last, m.index), marks: [] });
    const k = key();
    markDefs.push({ _type: "link", _key: k, href: m[2] });
    children.push({ _type: "span", _key: key(), text: m[1], marks: [k] });
    last = m.index + m[0].length;
  }
  if (last < text.length) children.push({ _type: "span", _key: key(), text: text.slice(last), marks: [] });
  return { children, markDefs };
}

function toBlocks(source) {
  return source
    .trim()
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line) => {
      let style = "normal";
      let listItem;
      let text = line;
      if (line.startsWith("### ")) [style, text] = ["h3", line.slice(4)];
      else if (line.startsWith("## ")) [style, text] = ["h2", line.slice(3)];
      else if (line.startsWith("> ")) [style, text] = ["blockquote", line.slice(2)];
      else if (line.startsWith("- ")) [listItem, text] = ["bullet", line.slice(2)];
      return {
        _type: "block",
        _key: key(),
        style,
        ...(listItem && { listItem, level: 1 }),
        ...spans(text),
      };
    });
}

