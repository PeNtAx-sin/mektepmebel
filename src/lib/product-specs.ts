// slug стула на Z-ножке остался от старого названия «Стул школьный на 4 ножках Синий»
const BY_SLUG: Record<string, ProductDefaults> = {
  "stul-shkolnyi-na-4-nozhkakh-sinii": CHAIR_Z,
};

export function productDefaults(p: { slug: string; title: string }): ProductDefaults | null {
  if (BY_SLUG[p.slug]) return BY_SLUG[p.slug];
  if (/парта/i.test(p.title) && /двухместн/i.test(p.title)) return DESK_DOUBLE;
  if (/парта/i.test(p.title) && /одноместн/i.test(p.title)) return DESK_SINGLE;
  if (/z-образн|на z/i.test(p.title)) return CHAIR_Z;
  return null;
}
